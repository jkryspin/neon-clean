#!/usr/bin/env python3
"""Generate docs/decode-plan.md's living status tables from neon-protocol/opcodes.toml, so the plan can never go
stale the way a hand-written list would. Run after any registry change (registry-facts.py, correlate.py follow-up,
a hand edit) and before committing.

  scripts/decode-status.py > docs/decode-plan-tables.md   # or redirect into decode-plan.md's generated section

Classifies every opcode into a next-step bucket using cheap signals already in the registry text, so the plan
tells you WHAT TO TRY NEXT, not just WHAT IS KNOWN:
  - "name it"          status=verified/decoded, no name yet (rare - usually fields but no settled name)
  - "confirm family"   summary already proposes a family/meaning candidate, needs the stronger evidence rule
  - "re-run sweep"      status=structure/observed, no live-trigger mentioned, more passive data might resolve it
  - "needs live trigger" summary says a trigger is needed, or low traffic (<30 packets) makes passive stats weak
  - "needs binary analysis" high traffic (>1000 packets) AND passive tools have already been tried and logged
                          (summary mentions correlate.py/idscan/lifecycle) without reaching a name - these are the
                          ones where the client EXE itself is the next real lever, not more log-watching
"""
import re, sys

text = open("neon-protocol/opcodes.toml").read()
parts = re.split(r"(?=\[\[opcode\]\])", text)

def classify(b, count, named, status):
    low = b.lower()
    if named:
        return None  # not part of the todo list
    if "needs a second account" in low or "needs levels" in low or "trade needs" in low:
        return "needs live trigger (blocked on account/level)"
    if count < 30:
        return "needs live trigger (too little passive data)"
    tried_passive = any(p in low for p in ("correlate.py", "idscan", "lifecycle.py", "poscorr.py", "autocorr.py",
                                            "same-player gap", "0x03d4", "0x022d", "0x0209", "mob kill"))
    if tried_passive and count >= 1000:
        return "needs binary analysis (passive tools already tried)"
    if tried_passive:
        return "re-run sweep as data grows"
    if "plausible" in low or "candidate" in low or "likely" in low:
        return "confirm family (independent cross-check needed)"
    return "re-run sweep (not yet tried against landmarks)"

rows = []
for b in parts:
    idm = re.search(r'^id = (0x[0-9a-f]+)\n', b, re.M)
    if not idm:
        continue
    dirm = re.search(r'^dir = "(\w+)"', b, re.M)
    if not dirm:
        continue
    named = re.search(r'^name = ', b, re.M) is not None
    name = re.search(r'^name = "([^"]+)"', b, re.M)
    status = re.search(r'^status = "(\w+)"', b, re.M)
    cnt = re.search(r'FACTS \(exact-decoded logs, [0-9-]+\): (\d+) packets', b)
    count = int(cnt[1]) if cnt else 0
    has_fields = "field = [" in b
    next_step = classify(b, count, named, status[1] if status else "?")
    rows.append({
        "id": idm[1], "dir": dirm[1], "named": named, "name": name[1] if name else None,
        "status": status[1] if status else "?", "count": count, "has_fields": has_fields, "next_step": next_step,
    })

incoming = [r for r in rows if r["dir"] == "in"]
outgoing = [r for r in rows if r["dir"] == "out"]
wire = [r for r in rows if r["dir"] == "wire"]

def pct(n, d):
    return f"{100*n/d:.0f}%" if d else "0%"

print("<!-- GENERATED by scripts/decode-status.py - do not hand-edit this block, re-run the script instead -->")
print()
print(f"Incoming: {sum(r['named'] for r in incoming)}/{len(incoming)} named ({pct(sum(r['named'] for r in incoming), len(incoming))}). "
      f"Outgoing: {sum(r['named'] for r in outgoing)}/{len(outgoing)} named ({pct(sum(r['named'] for r in outgoing), len(outgoing))}).")
print()

todo = sorted([r for r in incoming if not r["named"]], key=lambda r: -r["count"])
print(f"## Incoming opcodes still unnamed ({len(todo)})")
print()
print("| opcode | status | packets | next step |")
print("|---|---|---|---|")
for r in todo:
    print(f"| `{r['id']}` | {r['status']} | {r['count']} | {r['next_step']} |")

print()
todo_out = sorted([r for r in outgoing if not r["named"]], key=lambda r: -r["count"])
print(f"## Outgoing opcodes still unnamed ({len(todo_out)})")
print()
print("| opcode | status | packets | next step |")
print("|---|---|---|---|")
for r in todo_out:
    print(f"| `{r['id']}` | {r['status']} | {r['count']} | {r['next_step']} |")

print()
named_in = [r for r in incoming if r["named"]]
no_encoder = [r for r in named_in if r["has_fields"]]  # has fields decoded but (today) no Rust encoder exists for any opcode
print(f"## Named incoming opcodes with fields (encode-ready candidates): {len(no_encoder)}")
print("None of these have a Rust encoder yet (neon-protocol only decodes). Building `Registry`-driven encode is the")
print("Tier B replay blocker - see docs/decode-plan.md.")
print()
for r in no_encoder:
    print(f"- `{r['id']}` {r['name']}")
