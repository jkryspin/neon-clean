#!/usr/bin/env python3
"""Merge neon-stream --opcode-log files into docs/opcodes.md.

  scripts/opcode-doc.py [run/opcodes/*.json]

Meanings come only from KNOWN (verified in docs/network-protocol.md); everything else is listed as observed-only.
Re-run after more capture time; the output is overwritten.
"""
import glob, json, sys, datetime

KNOWN = {
    0x03c9: ("mob spawn", "decoded"),
    0x03dc: ("mob update/move", "decoded (start position only)"),
    0x03d4: ("mob removed", "decoded"),
    0x044d: ("mob damaged", "layout known, unused"),
    0x022d: ("player spawn", "decoded (id, name)"),
    0x029d: ("player move", "decoded"),
    0x0471: ("drop spawn (own kills only)", "decoded"),
    0x0472: ("drop removed", "decoded"),
    0x007e: ("own stat update", "decoded (bitmask; some sizes unverified)"),
    0x008b: ("pickup message", "decoded"),
    0x0072: ("inventory change", "seen with pickups, not decoded"),
    0x0281: ("pet spawn", "name only"),
    0x0282: ("pet move", "name only"),
    0x00ae: ("chat / megaphone", "text"),
    0x00a7: ("party update", "decoded (create/leave/join)"),
}

import os, time
STRUCT = {
    # Structure read from captured payloads (jib01 in Amherst, 2026-10-26). Not meanings.
    0x0456: "busiest opcode in a crowded town; sizes 12 or 26+21n (n=1..5: 47,68,89,110,131): u16 op, u32 small counter, then 21-byte records",
    0x004f: "3 bytes: op + one byte (values 0/1 seen)",
    0x0028: "2 bytes: bare opcode, no fields, about 1 per 10 s",
    0x02db: "7 bytes: op + 5 bytes (10 0a 00 00 00 seen)",
    0x001b: "48 bytes, mostly zeros with two u64-looking values near the end; about 1 per 10 s",
}
import tomllib
REG = {}
try:
    for o in tomllib.load(open("neon-protocol/opcodes.toml", "rb"))["opcode"]:
        REG[(o["dir"], o["id"])] = o
except OSError:
    pass
paths = sys.argv[1:] or sorted(glob.glob("run/opcodes/*.json"))
# Capture length per log = file birth time to last rewrite (ctime would reset on every rewrite).
import subprocess
def _born(p):
    return int(subprocess.check_output(["stat", "-c", "%W", p]))
span = sum(max(1.0, os.stat(p).st_mtime - _born(p)) for p in paths)
agg = {}
for p in paths:
    for k, v in json.load(open(p)).items():
        a = agg.setdefault(int(k, 16), dict(count=0, min=10**9, max=0, total=0))
        a["count"] += v["count"]; a["total"] += v["total_len"]
        a["min"] = min(a["min"], v["min_len"]); a["max"] = max(a["max"], v["max_len"])

out = [
    "# Opcode reference",
    "",
    f"Generated by `scripts/opcode-doc.py` on {datetime.date.today()} from {len(paths)} `--opcode-log` file(s). "
    "Do not edit by hand; verified field layouts live in `docs/network-protocol.md`.",
    "",
    "## Incoming (server -> client)",
    "",
    "Counts and sizes are what the passive capture actually saw (sizes include the 2-byte opcode). "
    "\"Meaning\" is filled only for opcodes whose layout was verified against the live client; "
    "everything else is deliberately left unnamed rather than guessed from other MapleStory versions.",
    "",
    "| Opcode | Seen | Per min | Size (min-max) | Meaning | Status |",
    "|---|---:|---:|---|---|---|",
]
for op in sorted(agg):
    a = agg[op]
    r = REG.get(("in", op), {})
    name = r.get("name", "")
    status = r.get("status", "observed") + (": " + r["summary"] if r.get("summary") else "")
    size = f"{a['min']}" if a["min"] == a["max"] else f"{a['min']}-{a['max']}"
    per_min = a["count"] / span * 60 / max(1, len(paths))
    if r.get("status", "observed") == "observed" and a["min"] == a["max"] and per_min >= 5:
        status = "observed; fixed-size and frequent (heartbeat-like)"
    out.append(f"| `0x{op:04x}` | {a['count']} | {per_min:.1f} | {size} | {name} | {status} |")
missing = sorted(o for (d, o), v in REG.items() if d == "in" and v["status"] in ("verified", "decoded") and o not in agg)
if missing:
    out += ["", "Documented but not seen in these logs: " + ", ".join(f"`0x{o:04x}`" for o in missing) + "."]
try:
    og = json.load(open("docs/outgoing-opcodes.json"))
    cap = og.get("_capture", "")
    ops = og["opcodes"]
except OSError:
    ops, cap = {}, ""
out += [
    "",
    "## Outgoing (client -> server)",
    "",
    "The payload cipher is not broken; instead the opcode is read from the client's own packet object just before it is "
    "encrypted (breakpoint on the game's send-packet function, see `docs/network-protocol.md`, \"Outgoing plaintext\"). "
    f"Source: `docs/outgoing-opcodes.json` ({cap}). Counts only: payload bytes are not stored because some packets carry "
    "the launcher login token. \"Next-send wire lengths\" are the wire length (4-byte header + payload) of the send that followed, "
    "which is only approximate for queued or bulk packets. Notes are given only where the evidence is in the table itself.",
    "",
    "| Opcode | Seen | Next-send wire lengths | Note |",
    "|---|---:|---|---|",
]
NOTE = {
    "0x02fe": "most frequent by far; payload carries a small incrementing counter: probably movement (unverified)",
    "0x00de": "bare opcode, no fields",
    "0x0155": "bare opcode, no fields",
    "0x02f0": "bare opcode, no fields",
    "0x0073": "launcher login string (handshake); contains a session token",
    "0x0070": "carries a GUID string; probably a client/session id",
    "0x008f": "text log line (\"ELog|..|VERSION...\")",
    "0x0090": "text log lines, bulk",
    "0x0077": "bulk, ~1460 bytes",
}
for k in sorted(ops):
    v = ops[k]
    lens = ", ".join(f"{l}x{n}" if n > 1 else l for l, n in sorted(v["next_send_wire_lens"].items(), key=lambda t: int(t[0])))
    ro = REG.get(("out", int(k, 16)), {})
    note = ro.get("summary") or NOTE.get(k, "")
    out.append(f"| `{k}` | {v['count']} | {lens[:70]}{'...' if len(lens) > 70 else ''} | {note} |")
out += ["", f"Total: {len(ops)} distinct outgoing opcodes, {sum(v['count'] for v in ops.values())} packets in one short capture; "
        "rarer actions (chat, NPC, shop, skills, party) have not been triggered yet and are absent.", ""]
open("docs/opcodes.md", "w").write("\n".join(out))
print(f"wrote docs/opcodes.md: {len(agg)} incoming, {len(ops)} outgoing opcodes")
