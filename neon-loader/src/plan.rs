        // 2026-10-26 (a Monday) 09:30 UTC, plan in UTC.
        let monday_0930 = 1_792_920_600_000u64 - (1_792_920_600_000u64 % 86_400_000) + (9 * 60 + 30) * MIN;
        let mut p = plan(vec![Step::Rest { minutes: 1 }]);
